#!/usr/bin/env python3
"""Parse the transport-owned cc-connect request context header.

The header is generated by the local cc-connect binary before the user message
is passed to Codex.  It is deliberately small: no message body, credentials,
or display names are persisted in Uroad task records.
"""
from __future__ import annotations

import re
from typing import Mapping


class RequestContextError(ValueError):
    """Raised when a caller supplies an invalid or conflicting context."""


_HEADER = re.compile(
    r'^\[cc-connect request_context_v=1 '
    r'sender_id=(?P<sender_id>[^\s\]]+) '
    r'(?:sender_name="[^"\r\n]*" )?'
    r'platform=(?P<platform>[^\s\]]+) '
    r'chat_id=(?P<chat_id>[^\s\]]+) '
    r'message_id=(?P<message_id>[^\s\]]+) '
    r'thread_id=(?P<thread_id>[^\s\]]*)\]$'
)


def metadata_from_context_header(header: str) -> dict:
    """Return canonical Uroad metadata from one cc-connect context line."""
    match = _HEADER.fullmatch((header or "").strip())
    if not match:
        raise RequestContextError("CC Connect 请求上下文格式无效；请从机器人消息首行原样传递 request_context")
    fields = match.groupdict()
    if fields["platform"] != "feishu":
        raise RequestContextError("Uroad 当前仅接受飞书 CC Connect 请求上下文")
    for field in ("sender_id", "chat_id", "message_id"):
        if not fields[field]:
            raise RequestContextError(f"CC Connect 请求上下文缺少 {field}")
    return {
        "requester": {"id": fields["sender_id"]},
        "source": {"chatId": fields["chat_id"], "messageId": fields["message_id"]},
        "routing": {"threadId": fields["thread_id"] or None},
        "raw": {
            "requesterId": fields["sender_id"],
            "chatId": fields["chat_id"],
            "messageId": fields["message_id"],
            "threadId": fields["thread_id"] or None,
            "platform": fields["platform"],
        },
    }


def merge_transport_metadata(context: Mapping[str, object], supplied: Mapping[str, object] | None = None) -> dict:
    """Keep transport identity authoritative while retaining non-identity hints."""
    result = {key: value for key, value in dict(supplied or {}).items() if key not in {"requester", "source", "routing"}}
    supplied_raw = result.get("raw")
    raw = dict(supplied_raw) if isinstance(supplied_raw, dict) else {}
    transport_raw = dict(context.get("raw") or {})
    for key in ("requesterId", "chatId", "messageId", "threadId"):
        if raw.get(key) not in (None, "", transport_raw.get(key)):
            raise RequestContextError(f"手工请求元数据不能覆盖 CC Connect {key}")
        raw[key] = transport_raw.get(key)
    raw["platform"] = transport_raw["platform"]
    result["raw"] = raw
    result["requester"] = dict(context["requester"])
    result["source"] = dict(context["source"])
    result["routing"] = dict(context["routing"])
    return result


def followup_identity_from_context(header: str) -> dict:
    metadata = metadata_from_context_header(header)
    return {
        "requester_id": metadata["requester"]["id"],
        "chat_id": metadata["source"]["chatId"],
        "thread_id": metadata["routing"].get("threadId") or "",
        "message_id": metadata["source"]["messageId"],
    }